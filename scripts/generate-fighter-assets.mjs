// Derive small, transparent PNG backups from existing local artwork only.
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import {runtimeHeroes} from '../src/runtime-heroes.js';
import {ACTIVE_ROSTER,lookupRuntimeHero} from '../src/hero-registry.js';
const atlas=JSON.parse(fs.readFileSync(new URL('../assets/atlas.json',import.meta.url)));
const entries={};
for(const hero of runtimeHeroes){
 const a=atlas.heroes[hero.id];
 if(!a&&!ACTIVE_ROSTER.heroIds.some(id=>lookupRuntimeHero(runtimeHeroes,id).id===hero.id))continue;
 const raw=/^assets\/[a-z_]+-render\.png$/.test(hero.render);
 const fallback=raw?hero.render:`assets/fighters/${hero.id}.png`;
 entries[hero.id]={primary:a?{src:a.sheet||atlas.sheets[a.sheetId],frames:a.frames,referenceHeight:a.referenceHeight}:{src:hero.render},fallback:{src:fallback,...(a?{frame:[0,0,...a.frames[0].slice(2)],referenceHeight:a.referenceHeight}:{})}};
}
const python=`import json,sys
from pathlib import Path
from PIL import Image
for key,e in json.load(sys.stdin).items():
 p=e['primary']; im=Image.open(p['src']).convert('RGBA')
 if 'frames' in p:
  x,y,w,h,*_=p['frames'][0]; im=im.crop((x,y,x+w,y+h))
 alpha=im.getchannel('A'); assert alpha.getextrema()[0]<255 and alpha.getextrema()[1]>0, key+' lacks transparency'
 out=Path(e['fallback']['src']); out.parent.mkdir(parents=True,exist_ok=True); im.save(out,optimize=True)
`;
execFileSync(process.env.PYTHON||'python3',['-c',python],{cwd:new URL('../',import.meta.url),input:JSON.stringify(entries)});
fs.writeFileSync(new URL('../src/fighter-sprites.js',import.meta.url),'// Generated by scripts/generate-fighter-assets.mjs from existing transparent assets.\nexport const FIGHTER_SPRITES='+JSON.stringify(entries,null,2)+';\n');
console.log(JSON.stringify({fighterBackups:Object.keys(entries).length}));
